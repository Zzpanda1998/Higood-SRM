const currencyOf = (currency: string): MaterialPaymentCurrency => currency === "USD" ? "USD" : currency === "IDR" ? "IDR" : "CNY";
const amountText = (value: number, currency: MaterialPaymentCurrency) => {
  if (currency === "CNY") return value >= 10000 ? "壹万捌仟陆佰元整" : "捌仟伍佰元整";
  if (currency === "USD") return "壹仟贰佰伍拾美元整";
  return "伍仟柒佰玖拾万印尼盾整";
};
const packageQty = (baseQty: number, unit: string) => unit === "米" ? Math.ceil(baseQty / 45) : unit === "个" ? Math.ceil(baseQty / 100) : Math.ceil(baseQty / 50);

